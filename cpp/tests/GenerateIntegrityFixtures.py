"""Regenerate small, public test ZIPs using Python's independent ZIP implementation."""
import base64,io,struct,zipfile
from pathlib import Path
def archive(method,descriptor=False):
    class Stream(io.BytesIO):
        def seekable(self):return False
        def seek(self,*args):raise io.UnsupportedOperation()
    stream=Stream() if descriptor else io.BytesIO()
    with zipfile.ZipFile(stream,'w',compression=method) as z:
        z.writestr('word/document.xml',b'<document>This is a public integrity test.</document>')
        z.writestr('empty.txt',b'')
    return stream.getvalue()
stored=archive(zipfile.ZIP_STORED)
deflated=archive(zipfile.ZIP_DEFLATED)
def mutate_body(value):
    value=bytearray(value); start=30+struct.unpack_from('<H',value,26)[0]+struct.unpack_from('<H',value,28)[0]
    value[start+7]^=0x80;return bytes(value)
central=stored.index(b'PK\x01\x02')
encrypted=bytearray(stored)
for offset in (6,central+8):struct.pack_into('<H',encrypted,offset,struct.unpack_from('<H',encrypted,offset)[0]|1)
large=bytearray(stored);struct.pack_into('<I',large,central+24,8*1024*1024)
broken_offset=bytearray(stored);struct.pack_into('<I',broken_offset,central+42,0xfffffffe)
fixtures=[('stored',stored,1),('deflated',deflated,1),('descriptor',archive(zipfile.ZIP_DEFLATED,True),1),
          ('stored-body-corrupt',mutate_body(stored),2),('deflated-body-corrupt',mutate_body(deflated),2),
          ('truncated',stored[:-3],2),('encrypted',bytes(encrypted),3),('expanded-budget',bytes(large),3),
          ('invalid-local-offset',bytes(broken_offset),2),('unsupported-bzip2',archive(zipfile.ZIP_BZIP2),3)]
lines=['#pragma once','// Generated by GenerateIntegrityFixtures.py; fixture payloads contain no secrets.',
       'struct IntegrityFixture { const char* name; const char* base64; int expected; };','inline constexpr IntegrityFixture integrityFixtures[] = {']
lines += ['    {"'+name+'","'+base64.b64encode(data).decode()+'",'+str(expected)+'},' for name,data,expected in fixtures]
lines+=['};','']
Path(__file__).with_name('IntegrityFixtures.h').write_text('\n'.join(lines),encoding='utf-8')
